/**
 * `npm run evals:report`: rebuilds evals/results/summary.json from the saved runs, then writes docs/EVALS.md from it.
 * Nothing is typed by hand: re-run the evals, then this, and the document follows.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { buildSummary } from "./summary";

const ROOT = join(__dirname, "..", "..");
const s = buildSummary();
writeFileSync(join(ROOT, "evals/results/summary.json"), JSON.stringify(s, null, 2) + "\n");

const label = (c: string) => c.replace(/_/g, " ").replace(/^./, (x) => x.toUpperCase()).replace(/chatgpt/i, "ChatGPT");
const lower = (c: string) => label(c).replace(/^./, (x) => x.toLowerCase());
const list = (xs: string[]) => (xs.length > 1 ? `${xs.slice(0, -1).join(", ")} and ${xs.at(-1)}` : xs[0] ?? "");
const frac = (n: number, d: number) => `${n}/${d}`;
const pct = (n: number, d: number) => `${Math.round((n / d) * 100)}%`;
const usd = (n: number | null) => (n === null ? "n/a" : `$${n.toFixed(n < 0.01 ? 5 : 2)}`);
const date = (iso: string) => new Date(iso).toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric", timeZone: "Asia/Kolkata" });
const quote = (t: string) => `> ${t.replace(/\s+/g, " ").trim()}`;
const lf = s.like_for_like;
const gateOk = s.gate.every((g) => g.passing);

const md: string[] = [];
md.push(
  "# How we test Cosmos AI",
  "",
  "_Generated by `npm run evals:report` from `evals/results/summary.json`. Don't edit by hand._",
  "",
  "## Summary",
  "",
  `- **${s.run.cases} cases across ${s.run.categories} categories**, run on ${date(s.run.v2_run_at)} (commit \`${s.run.v2_commit}\`).`,
  `- Agent model: \`${s.run.agent_model}\` (fallback \`${s.run.fallback_model}\`). Judge model: \`${s.run.judge_model}\`, a different tier.`,
  ...(s.run.judge_unavailable.ids.length ? [`- The judge scored ${s.run.judged} of ${s.run.cases} cases. ${s.run.not_judged_by_design} have fixed lines (input limits, abuse) and aren't judged by design; ${s.run.judge_unavailable.ids.length} more (${s.run.judge_unavailable.ids.map((x) => "`" + x + "`").join(", ")}) weren't judged because ${s.run.judge_unavailable.reason}. All of them pass their rule checks. To fill them in: \`npm run evals:rejudge -- --from v2 --write --ids ${s.run.judge_unavailable.ids.join(",")}\`, then \`npm run evals:report\`.`] : []),
  `- Cost of a full run: **${usd(s.run.full_run_cost_usd)}** (agent ${usd(s.run.agent_cost_usd)} + judge ${usd(s.run.judge_cost_usd)}; the judge is priced at the highest listed Pro rate, so it's an upper bound${s.run.judge_unavailable.ids.length ? ", and covers the judged cases only" : ""}).`,
  "",
  "## Headline",
  "",
  `**${pct(lf.v1_pass, lf.cases)} → ${pct(lf.v2_pass, lf.cases)} on the same ${lf.cases} cases** (v1 ${frac(lf.v1_pass, lf.cases)} → v2 ${frac(lf.v2_pass, lf.cases)}).`,
  "",
  `- ${lf.unchanged.cases} of those cases are unchanged since v1: ${frac(lf.unchanged.v1_pass, lf.unchanged.cases)} → ${frac(lf.unchanged.v2_pass, lf.unchanged.cases)}.`,
  `- ${lf.reworded.cases} were reworded between runs (the check changed, e.g. a stricter required line or a checker false positive removed): ${frac(lf.reworded.v1_pass, lf.reworded.cases)} → ${frac(lf.reworded.v2_pass, lf.reworded.cases)}. Reworded: ${lf.reworded.ids.map((r) => `\`${r.id}\``).join(", ")}.`,
  `- **+${s.new_in_v2.cases} new cases, ${s.new_in_v2.v2_pass === s.new_in_v2.cases ? "all passing" : `${s.new_in_v2.v2_pass} passing`}** (${s.new_in_v2.by_category.map((c) => `${lower(c.category)} ${c.cases}`).join(", ")}).`,
  "",
  "## By category",
  "",
  "| Category | v1 | v2 | Cases | What this checks |",
  "|---|---|---|---|---|",
  ...s.by_category.map((c) => `| ${label(c.category)}${c.gated ? " 🔒" : ""} | ${c.v1 ? frac(c.v1.pass, c.v1.cases) : "new"} | ${frac(c.v2.pass, c.v2.cases)} | ${c.v2.cases} | ${c.what_this_checks} |`),
  "",
  "🔒 = part of the safety gate. Pass = rule checks and, where the case is judged, the judge's verdict.",
  "",
  "## Safety gate",
  "",
  `${list(s.gate.map((g) => lower(g.category))).replace(/^./, (x) => x.toUpperCase())} must pass **100% of rule checks**, or \`npm run evals\` exits 1 and the commit is blocked: a green gate is a required step of the pre-commit checklist in BUILD_LOG.md (enforced by process, not a git hook). The gate uses the deterministic rule checks, not the judge.`,
  "",
  "| Gated category | Rule checks | Status |",
  "|---|---|---|",
  ...s.gate.map((g) => `| ${label(g.category)} | ${frac(g.rule_pass, g.cases)} | ${g.passing ? "✅ passing" : "❌ failing"} |`),
  "",
  `**Gate: ${gateOk ? "passing" : "FAILING"}.**`,
  "",
  "## Latency and cost",
  "",
  `- p50 **${(s.run.p50_ms / 1000).toFixed(1)}s**, p95 **${(s.run.p95_ms / 1000).toFixed(1)}s** per conversation (whole case, including multi-turn cases and code-answered ones).`,
  `- Agent cost per chat: **${usd(s.run.cost_per_chat_usd)}** on average (many chips and safety lines are answered in code at $0).`,
  "",
  "## Fixed between v1 and v2",
  "",
);
for (const e of [...s.fixed, ...s.findings]) {
  md.push(
    `### ${e.title} (\`${e.id}\`, ${e.kind.join(" + ")})`,
    "",
    `**Shopper:** ${e.question}`,
    "",
    `v1 (${e.v1.pass ? "pass" : "fail"}):`,
    quote(e.v1.reply),
    "",
    `v2 (${e.v2.pass ? "pass" : "fail"}):`,
    quote(e.v2.reply),
    "",
    `**What changed:** ${e.what_changed}`,
    "",
  );
}
md.push(
  "## How it's checked",
  "",
  "1. **Rule checks first** (deterministic, in code):",
  ...s.how_checked.rules.map((r) => `   - ${r}`),
  `2. **LLM judge for tone and helpfulness only.** ${s.how_checked.judge}`,
  `3. **Judge agreement with a hand-check of ${s.judge_check.cases.length} cases: ${s.judge_check.agreement}** (the v1 rubric agreed ${s.judge_check.v1_rubric_agreement}). ${s.judge_check.method}`,
  "",
  "## What we rejected",
  "",
  ...s.rejected.map((r) => `- ${r.what} **Fix:** ${r.fix}`),
  "",
  "## Limits",
  "",
  ...s.limits.map((l) => `- ${l}`),
  "",
  "## How to run",
  "",
  "```bash",
  ...s.how_to_run,
  "```",
  "",
  `The gate: after every run the script checks ${s.gated_categories.map((c) => `\`${c}\``).join(", ")}; if any of them is below 100% of rule checks it prints \`REGRESSION GATE FAILED\` and exits 1.`,
  "",
  "Abuse and prompt-injection cases are listed by category and count only; their text isn't quoted here.",
  "",
);

mkdirSync(join(ROOT, "docs"), { recursive: true });
writeFileSync(join(ROOT, "docs/EVALS.md"), md.join("\n"));
// README: the headline between the evals markers, so it never drifts from the data
const readmePath = join(ROOT, "README.md");
const readme = readFileSync(readmePath, "utf8");
const block = [
  "<!-- evals:start (generated by npm run evals:report) -->",
  `**${pct(lf.v1_pass, lf.cases)} → ${pct(lf.v2_pass, lf.cases)} on the same ${lf.cases} cases** (v1 → v2), **+${s.new_in_v2.cases} new cases, ${s.new_in_v2.v2_pass === s.new_in_v2.cases ? "all passing" : `${s.new_in_v2.v2_pass} passing`}**. Safety gate (${list(s.gate.map((g) => lower(g.category)))}): ${gateOk ? "passing" : "FAILING"}.`,
  "",
  "Full report, by category, with the fixes and limits: [docs/EVALS.md](docs/EVALS.md).",
  "<!-- evals:end -->",
].join("\n");
writeFileSync(readmePath, readme.replace(/<!-- evals:start[\s\S]*?<!-- evals:end -->/, block));

console.log(`wrote evals/results/summary.json, docs/EVALS.md and the README block (like-for-like ${lf.v1_pass}/${lf.cases} → ${lf.v2_pass}/${lf.cases}, +${s.new_in_v2.cases} new, gate ${gateOk ? "passing" : "FAILING"})`);
